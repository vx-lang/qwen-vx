"""Prints pf_flash_attention of src/prefill.vx: the attention of a chunk as one threadgroup mlir! block.

The design is that of llama.cpp's kernel_flash_attn_ext (ggml/src/ggml-metal/kernels/fa_common.metal),
MIT License, Copyright (c) 2023-2026 The ggml authors. Edit this script, not the generated MLIR:

    python3 scripts/mlir_kernels/flash_attention.py

prints the function; replace it in src/prefill.vx.
"""
ACC = '!gpu.mma_matrix<8x8xf32, "COp">'
AOP = '!gpu.mma_matrix<8x8xf16, "AOp">'
BOP = '!gpu.mma_matrix<8x8xf16, "BOp">'
KV = 'memref<?x?xf16, strided<[?, 1]>>'
L = []
e = L.append
e('/// att[t][h * 128 + d] = attention of query head h of token t (at position start + t) over the')
e('/// positions up to start + t, for t below n. A threadgroup does 8 tokens of one query head, in steps of')
e('/// 64 positions, as llama.cpp\'s kernel_flash_attn_ext. The caches are [position, 4, 128] f16.')
e('fn pf_flash_attention(att : &mut Tensor<f32, [?, ?], Memory::HBM>, q : &Tensor<f32, [?, ?, ?], Memory::HBM>, k_cache : &Tensor<f16, [?, ?, ?], Memory::HBM>, v_cache : &Tensor<f16, [?, ?, ?], Memory::HBM>, start : i32, n : i32, q_heads : i32, group : i32, scale : f32) -> void {')
e('  assert(q.extent(2) == 128 && k_cache.extent(2) == 128 && k_cache.extent(0) % 64 == 0 && start + n <= k_cache.extent(0), "pf_flash_attention: head_dim 128, and a KV cache of a multiple of 64 positions");')
e('  spawn on(Topology::Device) {')
e('    for qb in 0..(n + 7) / 8 across blocks {')
e('      for h in 0..q_heads across blocks {')
e('        let mut sq = unsafe { Tensor<f16, [1024], Memory::SMEM>::uninit() };')
e('        let mut so = unsafe { Tensor<f32, [1024], Memory::SMEM>::uninit() };')
e('        let mut ss = unsafe { Tensor<f32, [512], Memory::SMEM>::uninit() };')
e('        let mut sp = unsafe { Tensor<f16, [512], Memory::SMEM>::uninit() };')
e('        let _d = mlir!( threads : 128, inputs : (%sq = &mut sq : memref<1024xf16, 3>, %so = &mut so : memref<1024xf32, 3>, %ss = &mut ss : memref<512xf32, 3>, %sp = &mut sp : memref<512xf16, 3>, %att = att : memref<?x?xf32>, %q = q : memref<?x?x?xf32>, %k3 = k_cache : memref<?x?x?xf16>, %v3 = v_cache : memref<?x?x?xf16>, %start = start : i32, %n = n : i32, %group = group : i32, %scale = scale : f32, %qb = qb : i32, %h = h : i32), returns : i32, dialects : ["arith", "memref", "scf", "gpu", "vector", "math"], ensures : [writes_only(sq), writes_only(so), writes_only(ss), writes_only(sp), reads_only(q), reads_only(k_cache), reads_only(v_cache), writes_only(att[qb * 8..qb * 8 + 8][h * 128..h * 128 + 128])]) {')
b = lambda s: e('          ' + s)
for c in [0, 1, 2, 4, 8, 16, 32, 64, 128, 512]:
    b(f'%c{c} = arith.constant {c} : index')
b('%tid = gpu.thread_id x')
b('%sg = arith.divui %tid, %c32 : index')
b('%l = arith.remui %tid, %c32 : index')
b('%qbi = arith.index_cast %qb : i32 to index')
b('%hi = arith.index_cast %h : i32 to index')
b('%ni = arith.index_cast %n : i32 to index')
b('%starti = arith.index_cast %start : i32 to index')
b('%groupi = arith.index_cast %group : i32 to index')
b('%g = arith.divui %hi, %groupi : index')
b('%g128 = arith.muli %g, %c128 : index')
b('%P = memref.dim %k3, %c0 : memref<?x?x?xf16>')
b('%KH = memref.dim %k3, %c1 : memref<?x?x?xf16>')
b('%Wd = arith.muli %KH, %c128 : index')
b(f'%k = memref.reinterpret_cast %k3 to offset: [0], sizes: [%P, %Wd], strides: [%Wd, 1] : memref<?x?x?xf16> to {KV}')
b(f'%v = memref.reinterpret_cast %v3 to offset: [0], sizes: [%P, %Wd], strides: [%Wd, 1] : memref<?x?x?xf16> to {KV}')
b('%t0 = arith.muli %qbi, %c8 : index')
# Q: thread loads 8 floats of row j = tid / 16, columns (tid % 16) * 8, as f16 into sq; zeros so
b('%qj = arith.divui %tid, %c16 : index')
b('%qm = arith.remui %tid, %c16 : index')
b('%qc = arith.muli %qm, %c8 : index')
b('%qc4 = arith.addi %qc, %c4 : index')
b('%qt = arith.addi %t0, %qj : index')
b('%nm1 = arith.subi %ni, %c1 : index')
b('%qtc = arith.minui %qt, %nm1 : index')
b('%qlive = arith.cmpi ult, %qt, %ni : index')
b('%vz4 = arith.constant dense<0.0> : vector<4xf32>')
b('%q0r = vector.load %q[%qtc, %hi, %qc] {alignment = 16} : memref<?x?x?xf32>, vector<4xf32>')
b('%q1r = vector.load %q[%qtc, %hi, %qc4] {alignment = 16} : memref<?x?x?xf32>, vector<4xf32>')
b('%q0 = arith.select %qlive, %q0r, %vz4 : vector<4xf32>')
b('%q1 = arith.select %qlive, %q1r, %vz4 : vector<4xf32>')
b('%q0h = arith.truncf %q0 : vector<4xf32> to vector<4xf16>')
b('%q1h = arith.truncf %q1 : vector<4xf32> to vector<4xf16>')
b('%sqo = arith.muli %qj, %c128 : index')
b('%sqa = arith.addi %sqo, %qc : index')
b('%sqb = arith.addi %sqa, %c4 : index')
b('vector.store %q0h, %sq[%sqa] : memref<1024xf16, 3>, vector<4xf16>')
b('vector.store %q1h, %sq[%sqb] : memref<1024xf16, 3>, vector<4xf16>')
b('vector.store %vz4, %so[%sqa] : memref<1024xf32, 3>, vector<4xf32>')
b('vector.store %vz4, %so[%sqb] : memref<1024xf32, 3>, vector<4xf32>')
b('gpu.barrier')
# the positions: up to the last query of the tile
b('%tl = arith.addi %t0, %c8 : index')
b('%tlc = arith.minui %tl, %ni : index')
b('%lastq = arith.subi %tlc, %c1 : index')
b('%lastp = arith.addi %starti, %lastq : index')
b('%nblk0 = arith.divui %lastp, %c64 : index')
b('%nblk = arith.addi %nblk0, %c1 : index')
# rows of this simdgroup: j0 = sg, j1 = sg + 4; query positions
b('%j0 = arith.addi %sg, %c0 : index')
b('%j1 = arith.addi %sg, %c4 : index')
for jj in range(2):
    b(f'%qt{jj} = arith.addi %t0, %j{jj} : index')
    b(f'%qp{jj} = arith.addi %starti, %qt{jj} : index')
b('%neg = arith.constant -3.0e38 : f32')
b('%zero = arith.constant 0.0 : f32')
b('%l2 = arith.muli %l, %c2 : index')
b('%l4 = arith.muli %l, %c4 : index')
b('%zacc = gpu.subgroup_mma_constant_matrix %zero : ' + ACC)
b('%st:4 = scf.for %kb = %c0 to %nblk step %c1 iter_args(%M0 = %neg, %S0 = %zero, %M1 = %neg, %S1 = %zero) -> (f32, f32, f32, f32) {')
c = lambda s: e('            ' + s)
c('%p0 = arith.muli %kb, %c64 : index')
# Q K^T: simdgroup sg makes the 8 x 8 score tiles at key columns 8 sg and 8 sg + 32
for nc in range(2):
    c(f'%kc{nc}a = arith.muli %sg, %c8 : index')
    c(f'%kc{nc} = arith.addi %kc{nc}a, %c{32 * nc} : index')
    c(f'%kp{nc} = arith.addi %p0, %kc{nc} : index')
    c(f'%qk{nc} = scf.for %i = %c0 to %c16 step %c1 iter_args(%a = %zacc) -> ({ACC}) {{')
    d = lambda s: e('              ' + s)
    d('%d0 = arith.muli %i, %c8 : index')
    d(f'%mq = gpu.subgroup_mma_load_matrix %sq[%d0] {{leadDimension = 128 : index}} : memref<1024xf16, 3> -> {AOP}')
    d('%kd = arith.addi %g128, %d0 : index')
    d(f'%mk = gpu.subgroup_mma_load_matrix %k[%kp{nc}, %kd] {{leadDimension = 0 : index, transpose}} : {KV} -> {BOP}')
    d(f'%a2 = gpu.subgroup_mma_compute %mq, %mk, %a : {AOP}, {BOP} -> {ACC}')
    d(f'scf.yield %a2 : {ACC}')
    c('}')
    c(f'gpu.subgroup_mma_store_matrix %qk{nc}, %ss[%kc{nc}] {{leadDimension = 64 : index}} : {ACC}, memref<512xf32, 3>')
c('gpu.barrier')
# online softmax: rows j0, j1 of this simdgroup; lane l takes columns 2l, 2l + 1
outs = []
for jj in range(2):
    c(f'%r{jj} = arith.muli %j{jj}, %c64 : index')
    c(f'%ia{jj} = arith.addi %r{jj}, %l2 : index')
    c(f'%ib{jj} = arith.addi %ia{jj}, %c1 : index')
    c(f'%sa{jj}r = memref.load %ss[%ia{jj}] : memref<512xf32, 3>')
    c(f'%sb{jj}r = memref.load %ss[%ib{jj}] : memref<512xf32, 3>')
    c(f'%sa{jj}s = arith.mulf %sa{jj}r, %scale : f32')
    c(f'%sb{jj}s = arith.mulf %sb{jj}r, %scale : f32')
    c(f'%pa{jj} = arith.addi %p0, %l2 : index')
    c(f'%pb{jj} = arith.addi %pa{jj}, %c1 : index')
    c(f'%oka{jj} = arith.cmpi ule, %pa{jj}, %qp{jj} : index')
    c(f'%okb{jj} = arith.cmpi ule, %pb{jj}, %qp{jj} : index')
    c(f'%sa{jj} = arith.select %oka{jj}, %sa{jj}s, %neg : f32')
    c(f'%sb{jj} = arith.select %okb{jj}, %sb{jj}s, %neg : f32')
    c(f'%mx{jj} = arith.maxnumf %sa{jj}, %sb{jj} : f32')
    c(f'%bm{jj} = gpu.subgroup_reduce maxnumf %mx{jj} : (f32) -> f32')
    c(f'%Mn{jj} = arith.maxnumf %M{jj}, %bm{jj} : f32')
    c(f'%dm{jj} = arith.subf %M{jj}, %Mn{jj} : f32')
    c(f'%ms{jj} = math.exp %dm{jj} : f32')
    c(f'%ea{jj} = arith.subf %sa{jj}, %Mn{jj} : f32')
    c(f'%eb{jj} = arith.subf %sb{jj}, %Mn{jj} : f32')
    c(f'%xa{jj} = math.exp %ea{jj} : f32')
    c(f'%xb{jj} = math.exp %eb{jj} : f32')
    c(f'%xs{jj} = arith.addf %xa{jj}, %xb{jj} : f32')
    c(f'%bs{jj} = gpu.subgroup_reduce add %xs{jj} : (f32) -> f32')
    c(f'%Ss{jj} = arith.mulf %S{jj}, %ms{jj} : f32')
    c(f'%Sn{jj} = arith.addf %Ss{jj}, %bs{jj} : f32')
    c(f'%ha{jj} = arith.truncf %xa{jj} : f32 to f16')
    c(f'%hb{jj} = arith.truncf %xb{jj} : f32 to f16')
    c(f'memref.store %ha{jj}, %sp[%ia{jj}] : memref<512xf16, 3>')
    c(f'memref.store %hb{jj}, %sp[%ib{jj}] : memref<512xf16, 3>')
    # rescale this row of O: lane l takes 4 values
    c(f'%or{jj} = arith.muli %j{jj}, %c128 : index')
    c(f'%oi{jj} = arith.addi %or{jj}, %l4 : index')
    c(f'%ov{jj} = vector.load %so[%oi{jj}] : memref<1024xf32, 3>, vector<4xf32>')
    c(f'%msv{jj} = vector.broadcast %ms{jj} : f32 to vector<4xf32>')
    c(f'%ow{jj} = arith.mulf %ov{jj}, %msv{jj} : vector<4xf32>')
    c(f'vector.store %ow{jj}, %so[%oi{jj}] : memref<1024xf32, 3>, vector<4xf32>')
    outs += [f'%Mn{jj}', f'%Sn{jj}']
c('gpu.barrier')
# P V: simdgroup sg owns the output columns 8 sg + 32 ii, ii = 0..3
for ii in range(4):
    c(f'%dv{ii}a = arith.muli %sg, %c8 : index')
    c(f'%dv{ii} = arith.addi %dv{ii}a, %c{32 * ii if 32 * ii in (0, 32, 64, 128) else 0} : index' if ii in (0, 1, 2) else f'%dv{ii}b = arith.constant 96 : index')
    if ii == 3:
        c(f'%dv{ii} = arith.addi %dv{ii}a, %dv{ii}b : index')
    c(f'%o{ii}i = gpu.subgroup_mma_load_matrix %so[%dv{ii}] {{leadDimension = 128 : index}} : memref<1024xf32, 3> -> {ACC}')
    c(f'%vd{ii} = arith.addi %g128, %dv{ii} : index')
    c(f'%o{ii} = scf.for %kk = %c0 to %c8 step %c1 iter_args(%o = %o{ii}i) -> ({ACC}) {{')
    d = lambda s: e('              ' + s)
    d('%k8 = arith.muli %kk, %c8 : index')
    d(f'%mp = gpu.subgroup_mma_load_matrix %sp[%k8] {{leadDimension = 64 : index}} : memref<512xf16, 3> -> {AOP}')
    d('%vp = arith.addi %p0, %k8 : index')
    d(f'%mv = gpu.subgroup_mma_load_matrix %v[%vp, %vd{ii}] {{leadDimension = 0 : index}} : {KV} -> {BOP}')
    d(f'%onx = gpu.subgroup_mma_compute %mp, %mv, %o : {AOP}, {BOP} -> {ACC}')
    d(f'scf.yield %onx : {ACC}')
    c('}')
    c(f'gpu.subgroup_mma_store_matrix %o{ii}, %so[%dv{ii}] {{leadDimension = 128 : index}} : {ACC}, memref<1024xf32, 3>')
c('gpu.barrier')
c('scf.yield ' + ', '.join(outs) + ' : f32, f32, f32, f32')
b('}')
# epilogue: the rows of this simdgroup, divided by their sums
b('%h128 = arith.muli %hi, %c128 : index')
b('%one = arith.constant 1.0 : f32')
for jj in range(2):
    b(f'%inv{jj} = arith.divf %one, %st#{2 * jj + 1} : f32')
    b(f'%iv{jj} = vector.broadcast %inv{jj} : f32 to vector<4xf32>')
    b(f'%fr{jj} = arith.muli %j{jj}, %c128 : index')
    b(f'%fi{jj} = arith.addi %fr{jj}, %l4 : index')
    b(f'%fv{jj} = vector.load %so[%fi{jj}] : memref<1024xf32, 3>, vector<4xf32>')
    b(f'%fw{jj} = arith.mulf %fv{jj}, %iv{jj} : vector<4xf32>')
    b(f'%live{jj} = arith.cmpi ult, %qt{jj}, %ni : index')
    b(f'%ac{jj} = arith.addi %h128, %l4 : index')
    b(f'scf.if %live{jj} {{')
    b(f'  vector.store %fw{jj}, %att[%qt{jj}, %ac{jj}] {{alignment = 16}} : memref<?x?xf32>, vector<4xf32>')
    b('}')
b('macro.yield %qb : i32')
e('        };')
e('      }')
e('    }')
e('  }')
e('  return;')
e('}')
kernel = '\n'.join(L) + '\n'
print(kernel, end='')
